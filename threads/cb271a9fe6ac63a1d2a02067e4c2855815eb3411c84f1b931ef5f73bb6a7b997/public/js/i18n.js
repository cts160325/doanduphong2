let lang = localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'vi';

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'vi';
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.lang = lang;
  return lang;
}

export function toggleLang() {
  return setLang(lang === 'vi' ? 'en' : 'vi');
}

export function t(key, vars) {
  const value = key.split('.').reduce((acc, part) => (acc == null ? acc : acc[part]), dict[lang]);
  const fallback = key.split('.').reduce((acc, part) => (acc == null ? acc : acc[part]), dict.vi);
  let text = typeof value === 'string' ? value : typeof fallback === 'string' ? fallback : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}

export function errorMessage(code, meta) {
  const key = `err.${code}`;
  const text = t(key, meta);
  return text === key ? t('err.generic') : text;
}

const numberFormat = () => new Intl.NumberFormat(dict[lang].locale);

export function formatNumber(value) {
  return numberFormat().format(Number(value) || 0);
}

export function formatMoney(value) {
  return new Intl.NumberFormat(dict[lang].locale, {
    style: 'currency',
    currency: 'VND',
    maximumFractionDigits: 0,
  }).format(Number(value) || 0);
}

export function formatDate(iso, options = { day: '2-digit', month: 'short', year: 'numeric' }) {
  if (!iso) return '—';
  return new Intl.DateTimeFormat(dict[lang].locale, options).format(new Date(iso));
}

export function formatDateTime(iso) {
  return formatDate(iso, { day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' });
}

export function formatMonth(year, month) {
  return new Intl.DateTimeFormat(dict[lang].locale, { month: 'short' }).format(new Date(year, month - 1, 1));
}

/** Book titles are shared; descriptions and category labels come in both languages. */
export function localizedField(row, field) {
  if (!row) return '';
  const primary = row[`${field}_${lang}`];
  const fallback = row[`${field}_${lang === 'vi' ? 'en' : 'vi'}`];
  return primary || fallback || '';
}

export function hasLocalized(row, field) {
  return Boolean(row && row[`${field}_${lang}`]);
}

export function categoryName(row) {
  if (!row) return '';
  return localizedField(row, 'category') || localizedField(row, 'name') || '';
}

export function bookDescription(book) {
  return localizedField(book, 'description');
}

export function describeDaysLeft(loan) {
  if (!loan || loan.status !== 'active') return '';
  if (loan.overdue_days > 0) return t('account.overdue_days', { days: loan.overdue_days });
  if (loan.days_left <= 0) return t('account.due_today');
  return t('account.days_left', { days: loan.days_left });
}

export function statusLabel(status) {
  return t(`status.${status}`);
}
